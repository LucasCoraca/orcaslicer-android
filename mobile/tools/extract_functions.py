#!/usr/bin/env python3
"""Copies function definitions out of an upstream GUI source, so pure geometry that upstream keeps inside a wx/ImGui
class or a GUI translation unit (e.g. GLGizmoCut3D::its_make_groove_plane, EmbossJob.cpp's cut_surface) is compiled
unchanged by the mobile core.

usage: extract_functions.py <source.cpp> <ClassName|-> <NewClass|-> <out.inc> [--sub OLD NEW]... <function> [<function> ...]
A function given as "class Name" (or "struct" / "enum") copies that whole definition (nested ones too).
With a class, each function is found as "ClassName::function(" and "ClassName::" is renamed to "NewClass::"; with "-"
free functions are copied (a "template<...>" line right above is kept). A function given with its opening parenthesis
and the start of its parameter list (e.g. "get_extruders(bool conside_custom_gcode, const") picks one overload.
Declarations (a parameter list followed by ';') are skipped; the body is copied to its matching brace. The output is
#included by a file that declares what the bodies use. --sub replaces a literal text in the copied bodies (e.g. a
GUI-only expression); the build fails when the text is not found, so an upstream change is noticed.
--drop-lambdas PARAMS replaces every lambda whose parameter list starts with PARAMS (e.g. "const std::string&") by
nullptr, keeping a table's data without the GUI code of its callbacks (NativeCommands' runners).
"""
import re, sys

src, cls, new, out, *rest = sys.argv[1:]
subs, funcs, drop = [], [], []
while rest:
    if rest[0] == '--sub':
        subs.append((rest[1], rest[2]))
        rest = rest[3:]
    elif rest[0] == '--drop-lambdas':
        drop.append(rest[1])
        rest = rest[2:]
    else:
        funcs.append(rest.pop(0))
text = open(src, encoding='utf-8').read()


def matching(i, open_c, close_c):
    """the bracket closing the one at i; brackets in comments and string / character literals do not count"""
    depth = 0
    j = i
    n = len(text)
    while j < n:
        c = text[j]
        if c == '/' and text.startswith('//', j):
            j = text.find('\n', j)
            if j < 0:
                break
            continue
        if c == '/' and text.startswith('/*', j):
            j = text.find('*/', j) + 2
            if j < 2:
                break
            continue
        if c == '"' or c == "'":
            if c == '"' and j > 0 and text[j - 1] == 'R':   # raw string R"delim(...)delim"
                d = text[j + 1:text.index('(', j)]
                j = text.index(')' + d + '"', j) + len(d) + 2
                continue
            k = j + 1
            while k < n and text[k] != c:
                k += 2 if text[k] == '\\' else 1
            j = k + 1
            continue
        if c == open_c:
            depth += 1
        elif c == close_c:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    sys.exit(f'unbalanced {open_c} in {src}')


parts = [f'// generated by mobile/tools/extract_functions.py from {src.split("/src/")[-1]} — do not edit\n']
for f in funcs:
    if f.startswith(('class ', 'struct ', 'enum ')):   # a whole class / enum definition, up to its closing "};"
        m = re.search(r'^[ \t]*' + re.escape(f) + r'\b[^;{]*\{', text, re.M)   # nested definitions are indented
        if not m:
            sys.exit(f'{f} not found in {src}')
        end = matching(m.end() - 1, '{', '}')
        parts.append(text[m.start():end + 1] + ';\n')
        continue
    name = re.escape(f).replace(r'\ ', r'\s+') if '(' in f else re.escape(f) + r'\s*\('
    prefix = '' if cls == '-' else re.escape(cls) + r'::'
    found = None
    for m in re.finditer(r'^[^\n;{}#/]*' + (r'\b' if cls == '-' else r'\b') + prefix + name, text, re.M):
        if cls == '-' and re.search(r'::\s*$', text[m.start():m.end() - len(f.split('(')[0]) - 1]):
            continue   # a member function of the same name
        base = f.split('(')[0].strip()
        p = text.index('(', text.index(base, m.start() + (0 if cls == '-' else text[m.start():].index(cls + '::'))))
        e = matching(p, '(', ')')
        k = e + 1
        while k < len(text) and text[k] not in '{;':
            k += 1
        if k < len(text) and text[k] == '{':
            found = (m.start(), k)
            break
    if not found:
        sys.exit(f'{f} not found in {src}')
    start, body = found
    # keep a template<...> line right above, and a return type written on its own line ("std::tuple<...>\nCls::f()")
    prev_end = text.rfind('\n', 0, start)
    prev_start = text.rfind('\n', 0, prev_end) + 1
    prev = text[prev_start:prev_end].strip()
    if prev.startswith('template'):
        start = prev_start
    elif (text[start:].lstrip().startswith(cls + '::') if cls != '-' else False) and prev and \
            not prev.endswith((';', '{', '}', ')', ',')) and not prev.startswith(('//', '#', '/*', '*', '}', '{')) and '//' not in prev:
        start = prev_start
    end = matching(body, '{', '}')
    chunk = text[start:end + 1]
    if cls != '-':
        chunk = chunk.replace(cls + '::', new + '::')
    parts.append(chunk + '\n')
result = '\n'.join(parts)
for params in drop:
    # the lambdas, last first so earlier positions stay valid
    pat = re.compile(r'\[[^\[\]]*\]\s*\(\s*' + re.escape(params).replace(r'\ ', r'\s*') + r'[^)]*\)\s*(?:mutable\s*)?\{')
    found = list(pat.finditer(result))
    if not found:
        sys.exit(f'--drop-lambdas: no lambda takes {params}')
    text = result
    for m in reversed(found):
        end = matching(m.end() - 1, '{', '}')
        text = text[:m.start()] + 'nullptr' + text[end + 1:]
    result = text
for old, repl in subs:
    if old not in result:
        sys.exit(f'--sub text not found: {old}')
    result = result.replace(old, repl)
open(out, 'w', encoding='utf-8').write(result)
